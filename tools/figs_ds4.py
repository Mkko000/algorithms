# ---------------------------------------------------------------- trie (Fig 11.18)
def trie():
    words = {'am': 3, 'arc': 11, 'are': 7, 'arm': 9, 'art': 12, 'do': 8, 'dot': 15}
    def build(prefix):
        kids = []
        for c in sorted({w[len(prefix)] for w in words if w.startswith(prefix) and len(w) > len(prefix)}):
            kids.append(build(prefix + c))
            kids[-1].label = c
        v = words.get(prefix)
        return M([str(v)] if v is not None else [], kids, 'mnode hi' if v is not None else 'mnode')
    root = M([], [build(c) for c in sorted({w[0] for w in words})], 'mnode')
    for c, k in zip(sorted({w[0] for w in words}), root.kids): k.label = c
    F['ds22-trie'] = ('fig', mtree(root, kw=26, gap=12, dy=50, edge_labels=True) +
        '<figcaption>Trie لـ 7 كلمات (قيم الكتاب في Fig. 11.18). الحرف على الخط، والمربع الملوّن بيشيل القيمة لما كلمة تنتهي عنده، والنقطة = عقدة عبور. 11 عقدة (بالجذر) بدل 19 حرف.</figcaption>')


